# 카카오 REST API 키 입력 (앞뒤 공백 없이 붙여넣기)
KAKAO_API_KEY = ""

def clean_station_name(name):
    ''' 부역명 제거하고 **역**이 가장 마지막 텍스트라면 **역**을 추가한다 '''
    # 괄호 안 부역명 제거 (예: 서울대입구(관악구청) -> 서울대입구)
    base_name = re.sub(r'\(.*?\)', '', name).strip()
    # 이미 '역'으로 끝나는 경우 방지 (예: 서울역)
    if not base_name.endswith("역"):
        base_name += "역"
    return base_name

def get_coordinates(query):
    ''' 카카오 개발자 API url을 가져오고 각 역의 '''
    url = "https://dapi.kakao.com/v2/local/search/keyword.json"
    headers = {
        "Authorization": f"KakaoAK {KAKAO_API_KEY.strip()}"
    }
    # category_group_code='SW8' (지하철역 카테고리 고정으로 정확도 향상)
    params = {"query": query, "category_group_code": "SW8", "size": 1}
    
    try:
        res = requests.get(url, headers=headers, params=params)
        if res.status_code == 200:
            docs = res.json().get("documents", [])
            if docs:
                return float(docs[0]["y"]), float(docs[0]["x"])
            
            # 카테고리 지정 시 안 나오는 경우 일반 검색으로 1회 재시도
            params.pop("category_group_code")
            res_retry = requests.get(url, headers=headers, params=params)
            docs_retry = res_retry.json().get("documents", [])
            if docs_retry:
                return float(docs_retry[0]["y"]), float(docs_retry[0]["x"])
        else:
            print(f"[{query}] 오류 발생 (코드: {res.status_code}) -> {res.text}")
    except Exception as e:
        print(f"[{query}] 요청 에러: {e}")
        
    return None, None

print(f"총 {len(stations)}개 역 좌표 수집을 시작합니다...")
data = []

for i, st in enumerate(stations, 1):
    cleaned = clean_station_name(st)
    lat, lon = get_coordinates(cleaned)
    data.append({"역명": st, "검색어": cleaned, "위도": lat, "경도": lon})    

    print(f"진행 중... ({i}/{len(stations)}) - 최근 처리: {st} ({lat}, {lon})")
        
    time.sleep(SLEEP_TIME)  # API 속도 제한 방지

